"""Regenerate source/project-deaddraw/data/balance.json from the v3 sim's CONFIG.

    python3 projects/deaddraw/tools/regen_balance.py

Every number the game reads comes from tools/sim_deaddraw_v3.py CONFIG (the balance source of
truth); "extra_rules" holds display-only info and meta unlocks that the sim does not model and is
kept from the current file (falling back to the defaults below).
"""
import importlib.util
import json
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_file_location("sim", root + "/tools/sim_deaddraw_v3.py")
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)
path = root + "/source/project-deaddraw/data/balance.json"

DEFAULT_EXTRA = {
    "points_display_mult": 10,
    "score_hp_mult": 1,
    "survivor_info": {
        "rosa": {"role": "Mechanic", "unlocked": True},
        "imani": {"role": "Medic", "unlocked": True},
        "theo": {"role": "Courier", "unlocked": False},
    },
    "unlocks": {"downtown": ["survivor:theo"], "win": ["badge"]},
}

try:
    old = json.load(open(path))
except (OSError, ValueError):
    old = {}
extra = dict(DEFAULT_EXTRA)
if old.get("_version") == 3:
    extra.update(old.get("extra_rules", {}))

cfg = {
    "_note": "DeadDraw v3 (Kill Stacks). Generated by tools/regen_balance.py from "
             "tools/sim_deaddraw_v3.py CONFIG - edit the sim, then re-run. Points are sim units "
             "(the UI shows them x10).",
    "_version": 3,
}
cfg.update(m.CONFIG)
cfg["extra_rules"] = extra
open(path, "w").write(json.dumps(cfg, indent=2) + "\n")
print("ok", {k: cfg[k] for k in ("street_size", "actions", "points_on_kill", "finish_bonus",
                                 "melee_points", "run_damage", "safehouse_heal")})
