#!/usr/bin/env python3
"""Seeded sim/game parity cases for the DeadDraw v4 rules (board task dd-v4-impl).

Runs the rule functions of tools/sim_deaddraw_v4.py (the balance source of truth) on seeded
random situations and writes what they return to
source/project-deaddraw/tests/data/v4_parity.json. tests/test_v4_parity.gd replays every case
through the game's DDRun and checks it gets the same numbers:
  legal       every gun rule (incl. v4 small / heavy), random stacks, Rosa's Steady Hands
  challenge   every gun's challenge (incl. v4 Big Bang / Pest Control) on random stacks
  gun_kill    a gun kill: damage (Adrenaline / Grudge), points (finish bonus, Bounty, challenge,
              Show-Off), HP (Trophy Belt, heal rewards), Cover, gun kept (Encore) or gone
  melee       a melee kill with bare hands or a melee weapon (Brawler, Whetstone, Adrenaline,
              Grudge): damage and the uses left
  take        picking up a melee weapon card: uses (Whetstone, Brawler)
  salvage     swapping out an unfinished gun: points
  medkit      a medkit: HP and Cover after (Field Medic, Triage, Iron Stomach)
  room        room prices with and without Lockpick
  shop        the Safehouse Shop supplies: HP bought and points left behind
  mod_legal   v5 Gun Mods (economy-v5.md): legal_mod() for every rule x mod, random stacks / caps
  mod_fit     v5: fitting a Gun Mod to a slot with a gun on it (Short Barrel can finish it at once)

    python3 projects/deaddraw/tools/v4_parity_cases.py          # rewrite the fixture
    python3 projects/deaddraw/tools/v4_parity_cases.py --check  # exit 1 if it is stale
"""
from __future__ import annotations

import importlib.util
import json
import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "source", "project-deaddraw", "tests", "data", "v4_parity.json")
spec = importlib.util.spec_from_file_location("sim4", os.path.join(ROOT, "tools", "sim_deaddraw_v4.py"))
sim = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sim)
C = sim.CONFIG
RULES = ["any", "down", "up", "same", "close", "parity", "spread", "big", "zigzag", "small", "heavy"]
POWER_PATCHES = ["adrenaline", "grudge"]


def state(rng, passive="", patches=()):
    s = sim.State(20, passive)
    s.patches = set(patches)
    return s


def cases(seed=4):
    rng = random.Random(seed)
    out = {"_note": "Generated by tools/v4_parity_cases.py from tools/sim_deaddraw_v4.py; do not edit.",
           "seed": seed, "legal": [], "challenge": [], "gun_kill": [], "melee": [], "take": [], "salvage": [],
           "medkit": [], "room": [], "shop": [], "mod_legal": [], "mod_fit": []}
    for _ in range(400):
        rule = rng.choice(RULES)
        stack = [rng.randint(1, 12) for _ in range(rng.randint(0, 3))]
        z = rng.randint(1, 12)
        rosa = rng.random() < 0.3
        out["legal"].append({"rule": rule, "stack": stack, "z": z, "rosa": rosa,
                             "ok": bool(sim.legal(rule, tuple(stack), z, rosa))})
    wids = list(C["weapons"])
    for _ in range(300):
        wid = rng.choice(wids)
        cap = C["weapons"][wid]["cap"]
        stack = [rng.randint(1, 12) for _ in range(rng.randint(1, cap))]
        out["challenge"].append({"wid": wid, "stack": stack, "met": bool(sim.challenge_met(wid, tuple(stack)))})
    kill_patches = ["bounty", "trophy_belt", "show_off", "adrenaline", "grudge"]
    while len(out["gun_kill"]) < 250:
        wid = rng.choice(wids)
        w = C["weapons"][wid]
        stack = tuple(rng.randint(1, 12) for _ in range(rng.randint(0, w["cap"] - 1)))
        z = rng.randint(1, 12)
        if not sim.legal(w["rule"], stack, z, False):
            continue
        pt = [p for p in kill_patches if rng.random() < 0.35]
        s = state(rng, "", pt)
        s.hp = rng.randint(3, 20)
        s.slots[0] = (wid, w["rule"], w["p"], w["cap"], stack, False)
        hp0 = s.hp
        dmg = sim.weapon_damage(s, 0, z)
        sim.fight(s, z, 0)
        if s.hp <= 0:
            continue
        out["gun_kill"].append({"wid": wid, "stack": list(stack), "z": z, "patches": pt, "hp0": hp0, "damage": dmg,
                                "points": s.points, "hp": s.hp, "cover": s.cover, "kept": s.slots[0] is not None})
    mids = list(C["melee_weapons"])
    while len(out["melee"]) < 200:
        pt = [p for p in ["brawler", "whetstone"] + POWER_PATCHES if rng.random() < 0.35]
        s = state(rng, "", pt)
        s.hp = rng.randint(2, 20)
        mid = rng.choice(mids + [""])
        if mid:
            sim.apply_card(s, sim.Card("K", wid=mid), 0)
        z = rng.randint(1, 12)
        hp0 = s.hp
        uses0 = s.melee[2] if s.melee else 0
        dmg = sim.weapon_damage(s, 2, z)
        sim.fight(s, z, 2)
        if s.hp <= 0:
            continue
        out["melee"].append({"mid": mid, "patches": pt, "hp0": hp0, "z": z, "uses0": uses0, "damage": dmg,
                             "uses_after": s.melee[2] if s.melee else 0, "points": s.points})
    for mid in mids:
        for pt in ([], ["whetstone"], ["brawler"], ["whetstone", "brawler"]):
            s = state(rng, "", pt)
            sim.apply_card(s, sim.Card("K", wid=mid), 0)
            out["take"].append({"mid": mid, "patches": pt, "power": s.melee[1], "uses": s.melee[2]})
    for _ in range(60):
        wid = rng.choice(wids)
        w = C["weapons"][wid]
        stack = tuple(rng.randint(1, 12) for _ in range(rng.randint(0, w["cap"] - 1)))
        s = state(rng)
        s.slots[0] = (wid, w["rule"], w["p"], w["cap"], stack, False)
        sim.collect(s, 0, False)
        out["salvage"].append({"wid": wid, "stack": list(stack), "points": s.points})
    for _ in range(80):
        pt = [p for p in ("field_medic", "iron_stomach") if rng.random() < 0.5]
        passive = "triage" if rng.random() < 0.4 else ""
        s = state(rng, passive, pt)
        s.hp = rng.randint(1, 20)
        s.cover = rng.randint(0, 3)
        v = rng.randint(3, 6)
        hp0, cv0 = s.hp, s.cover
        sim.apply_card(s, sim.Card("M", v), None)
        out["medkit"].append({"v": v, "passive": passive, "patches": pt, "hp0": hp0, "cover0": cv0, "hp": s.hp, "cover": s.cover})
    for di, d in enumerate(C["districts"]):
        for ri, r in enumerate(d["rooms"]):
            for lp in (False, True):
                s = state(rng, "", ["lockpick"] if lp else [])
                out["room"].append({"district": di, "room": ri, "lockpick": lp, "cost": sim.room_price(s, dict(r))})
    for _ in range(60):
        s = state(rng)
        s.patches = set(C["patches"])       # no Patch to buy: only the supplies step is compared
        s.max_hp = 20
        s.hp = rng.randint(1, 20)
        s.points = rng.randint(0, 60)
        hp0, p0 = s.hp, s.points
        sim.heal(s, C["safehouse_heal"])
        st = sim.new_stats()
        sim.carry_over(s, st, rng)
        out["shop"].append({"hp0": hp0, "points0": p0, "bought": int(st["carry_converted"]), "lost": int(st["carry_lost"]),
                            "hp": s.hp, "points": s.points})
    mods = list(C["mods"])
    for _ in range(400):
        rule = rng.choice(RULES)
        mod = rng.choice(mods + [""])
        cap = rng.randint(1, 5)
        stack = [rng.randint(1, 12) for _ in range(rng.randint(0, cap - 1))]
        z = rng.randint(1, 12)
        rosa = rng.random() < 0.3
        out["mod_legal"].append({"rule": rule, "stack": stack, "z": z, "rosa": rosa, "mod": mod, "cap": cap,
                                 "ok": bool(sim.legal_mod(rule, tuple(stack), z, rosa, mod, cap))})
    for _ in range(80):
        wid = rng.choice(wids)
        w = C["weapons"][wid]
        mod = rng.choice(mods)
        stack = tuple(rng.randint(1, 12) for _ in range(rng.randint(0, w["cap"] - 1)))
        s = state(rng)
        s.slots[0] = (wid, w["rule"], w["p"], w["cap"], stack, False)
        sim.fit_mod_to(s, 0, mod)
        g = s.slots[0]
        out["mod_fit"].append({"wid": wid, "mod": mod, "stack": list(stack), "points": s.points,
                               "cap": g[3] if g else 0, "kept": g is not None})
    return out


def main():
    data = json.dumps(cases(), indent=1, sort_keys=True) + "\n"
    if "--check" in sys.argv:
        old = open(OUT).read() if os.path.exists(OUT) else ""
        print("up to date" if old == data else "STALE: re-run tools/v4_parity_cases.py")
        sys.exit(0 if old == data else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(data)
    print("wrote", OUT, {k: len(v) for k, v in cases().items() if isinstance(v, list)})


if __name__ == "__main__":
    main()
